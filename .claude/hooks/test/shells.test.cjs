test('every command the real PowerShell parser finds in a text is one the hook refuses when it is a refused command', { skip: !pwsh }, () => {
  const script = path.join(scratch, 'parse.ps1');
  const texts = path.join(scratch, 'texts.json');
  fs.writeFileSync(script, PARSE);
  fs.writeFileSync(texts, JSON.stringify(POWERSHELL));
  const run = spawnSync('pwsh', ['-NoProfile', '-File', script, '-File', texts], { encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr);
  const parsed = JSON.parse(run.stdout);
  assert.equal(parsed.length, POWERSHELL.length);
  const missed = [];
  let ran = 0;
  let quiet = 0;
  for (const [index, text] of POWERSHELL.entries()) {
    const names = parsed[index].names ?? [];
    const runs = (marker) => names.some((name) => new RegExp(`^${marker}$`).test(name));
    if (runs('Seen-[ABC]')) {
      ran++;
      if (!refused('PowerShell', text.replace(/Seen-[ABC]/g, 'tasklist').replace(/Hidden-A/g, 'Get-Date'))) missed.push(text);
    }
    if (text.includes('Hidden-A') && !runs('Hidden-A') && parsed[index].errors === 0) {
      quiet++;
      if (refused('PowerShell', text.replace(/Hidden-A/g, 'tasklist').replace(/Seen-[ABC]/g, 'Get-Date'))) missed.push(`refused although PowerShell runs nothing refused: ${text}`);
    }
  }
  assert.deepEqual(missed, []);
  assert.deepEqual([ran, quiet], [237, 13], 'texts where PowerShell runs a marked command, and texts where it leaves one alone');
});

test('every command bash really runs in a text is one the hook refuses when it is a refused command', { skip: !bashWorks }, () => {
  const missed = [];
  let ran = 0;
  let quiet = 0;
  for (const text of BASH) {
    const run = spawnSync(bash, ['-c', text], { cwd: scratch, encoding: 'utf8', timeout: 20000, input: '' });
    const said = `${run.stdout}\n${run.stderr.split(/\r?\n/).filter((line) => !/bash: -c: /.test(line)).join('\n')}`;
    if (/SEEN-[ABC]/.test(said)) {
      ran++;
      if (!refused('Bash', text.replace(/echo SEEN-[ABC]( >&2)?/g, 'tasklist').replace(/echo HIDDEN-A/g, 'date'))) missed.push(text);
    }
    if (text.includes('HIDDEN-A') && !/^HIDDEN-A$/m.test(said) && run.status === 0) {
      quiet++;
      if (refused('Bash', text.replace(/echo HIDDEN-A/g, 'tasklist').replace(/echo SEEN-[ABC]( >&2)?/g, 'date'))) missed.push(`refused although bash runs nothing refused: ${text}`);
    }
  }
  assert.deepEqual(missed, []);
  assert.deepEqual([ran, quiet], [181, 6], 'texts where bash runs a marked command, and texts where it leaves one alone');
});
