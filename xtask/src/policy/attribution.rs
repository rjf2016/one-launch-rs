use std::sync::LazyLock;

use regex::Regex;

const TOOLS: &str = "claude|anthropic|copilot|chatgpt|openai|gpt|codex|gemini|aider|devin|llm|ai";

static KINDS: LazyLock<Vec<(&'static str, Regex)>> = LazyLock::new(|| {
    let credited = format!(
        r"\b(?:generated|written|created|authored|produced|co-?authored|assisted)\s+(?:with|by|using)\s+(?:the\s+|an?\s+)?[^\w\s]*(?:{TOOLS})\b"
    );
    [
        (
            "a `Co-authored-by` trailer",
            r"^\s*co[-_ ]?authored[-_ ]?by\s*:",
        ),
        (
            "a trailer that credits a tool",
            r"^\s*(?:ai[-_ ])?(?:generated|assisted)[-_ ]by\s*:",
        ),
        ("a line that credits an AI tool", credited.as_str()),
        (
            "a link to an AI session",
            r"\b(?:claude\.ai/|claude\.com/claude-code|chatgpt\.com/|chat\.openai\.com/)",
        ),
    ]
    .into_iter()
    .map(|(kind, pattern)| {
        let pattern = Regex::new(&format!("(?i){pattern}")).expect("a fixed pattern");
        (kind, pattern)
    })
    .collect()
});

// A line is named by its number and by which kind it is, never quoted: the text is the author's.
pub fn lines(text: &str) -> Vec<(usize, &'static str)> {
    text.lines()
        .enumerate()
        .filter_map(|(index, line)| {
            let (kind, _) = KINDS.iter().find(|(_, pattern)| pattern.is_match(line))?;
            Some((index + 1, *kind))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    const TRAILER: &str = "a `Co-authored-by` trailer";
    const TOOL_TRAILER: &str = "a trailer that credits a tool";
    const CREDIT: &str = "a line that credits an AI tool";
    const LINK: &str = "a link to an AI session";

    fn kinds(text: &str) -> Vec<&'static str> {
        lines(text).into_iter().map(|(_, kind)| kind).collect()
    }

    #[test]
    fn a_co_author_trailer_is_found_whatever_its_case_and_spacing() {
        for line in [
            "Co-authored-by: Someone <someone@example.com>",
            "Co-Authored-By: Someone <someone@example.com>",
            "co-authored-by:Someone <someone@example.com>",
            "CO-AUTHORED-BY : Someone",
            "  Co-authored-by: Someone",
            "\tCo-authored-by\t: Someone",
            "Co-authored-by:",
            "Co_authored_by: Someone",
            "Co authored by: Someone",
            "Coauthored-by: Someone",
        ] {
            assert_eq!(kinds(line), [TRAILER], "{line}");
        }
        let message =
            "M1-F1: a subject\n\nA body.\r\n\r\nCo-authored-by: Someone <someone@example.com>\r\n";
        assert_eq!(lines(message), [(5, TRAILER)]);
    }

    #[test]
    fn a_tool_credit_is_found() {
        let with_a_link = format!(
            "\u{1f916} Generated with [Claude Code](https://{}/claude-code)",
            "claude.com"
        );
        for (line, kind) in [
            (with_a_link.as_str(), CREDIT),
            ("Generated with Claude Code", CREDIT),
            ("generated by ChatGPT", CREDIT),
            (
                "This commit was written by GitHub's copilot? No: Written by Copilot.",
                CREDIT,
            ),
            ("Created using an AI", CREDIT),
            ("Co-authored with **Claude**", CREDIT),
            ("Assisted by gpt-5", CREDIT),
            ("Generated-by: some tool", TOOL_TRAILER),
            ("Assisted-by: some tool", TOOL_TRAILER),
            ("AI-assisted-by: some tool", TOOL_TRAILER),
            ("See https://claude.ai/code/session_0123", LINK),
            ("https://chatgpt.com/share/abc", LINK),
        ] {
            assert_eq!(kinds(line), [kind], "{line}");
        }
    }

    #[test]
    fn prose_about_the_rule_and_ordinary_words_pass() {
        for line in [
            "M1-F6c: the attribution rule - no commit carries a `Co-authored-by` trailer",
            "GitHub's default squash message ends with a Co-authored-by: trailer naming the app",
            "The vectors were generated by running the TypeScript",
            "Generated with cargo metadata",
            "written by the agent, pushed by the owner",
            "Created using airflow",
            "the mail was generated by aide-de-camp",
            "Every Copilot comment is answered",
            "The drag rectangle is created by the cursor",
            "authored by the owner",
            "claude.aide/x and notclaude.ai/x",
            "Signed-off-by: Someone <someone@example.com>",
            "Reviewed-by: Someone",
            "",
        ] {
            assert_eq!(kinds(line), Vec::<&str>::new(), "{line}");
        }
    }
}
